    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:                                           
         String nombre = txtNombre.getText().trim();
    String creditosStr = txtCreditos.getText().trim();
    String cupoMaxStr = txtCupoMaximo.getText().trim();
    String estado = cbEstado.getSelectedItem().toString();
    if (nombre.isEmpty() || creditosStr.isEmpty() || cupoMaxStr.isEmpty() || estado.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        int creditos = Integer.parseInt(creditosStr);
        int cupoMax = Integer.parseInt(cupoMaxStr);
        
        if (!estado.equals("Activa") && !estado.equals("Finalizada") && !estado.equals("Suspendida")) {
            JOptionPane.showMessageDialog(this, "El estado debe ser: 'Activa', 'Finalizada' o 'Suspendida'.", "Estado Inválido", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Asignatura asig = new Asignatura(idSeleccionado, nombre, creditos, cupoMax, estado);
        
        if (asignaturaDAO.guardar(asig)) {
            JOptionPane.showMessageDialog(this, "Asignatura guardada con éxito.");
            limpiarCampos();
            cargarTabla();
        } else {
            JOptionPane.showMessageDialog(this, "Ocurrió un error al intentar guardar en MySQL.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Los créditos y el cupo máximo deben ser números enteros válidos.", "Formato Incorrecto", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if (idSeleccionado == 0) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione una asignatura de la tabla para eliminar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirmar = JOptionPane.showConfirmDialog(this,
                "¿Está seguro de eliminar de forma permanente la asignatura con ID " + idSeleccionado + "?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION);

        if (confirmar == JOptionPane.YES_OPTION) {
            if (asignaturaDAO.eliminar(idSeleccionado)) {
                JOptionPane.showMessageDialog(this, "Asignatura eliminada con éxito.");
                limpiarCampos();
                cargarTabla();
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo eliminar la asignatura. Verifique si está asignada a algún grupo.", "Error de integridad", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

