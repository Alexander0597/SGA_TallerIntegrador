    private void cargarTabla() {
       DefaultTableModel modelo = (DefaultTableModel) tblEstudiantes.getModel();
    modelo.setRowCount(0); // Vaciar filas**
    
    try {
        List<Estudiante> lista = estudianteDAO.listarTodos();
        for (Estudiante est : lista) {
            Object[] fila = new Object[] {
                est.getCi(),
                est.getNombre(),
                est.getApellidos(),
                est.getMail()
            };
            modelo.addRow(fila);
        }
        //Filtro para estudiantes
        trsFiltro = new TableRowSorter<>(modelo);
        tblEstudiantes.setRowSorter(trsFiltro);
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al cargar la tabla: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    }

