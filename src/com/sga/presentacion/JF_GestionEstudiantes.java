    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String ci = txtCi.getText().trim();
        String nombre = txtNombre.getText().trim();
        String apellidos = txtApellidos.getText().trim();
        String mail = txtMail.getText().trim();
        if (ci.isEmpty() || nombre.isEmpty() || apellidos.isEmpty() || mail.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // El ID se genera en base de datos de manera autoincremental, pasamos 0 provisoriamente
        Estudiante est = new Estudiante(ci, nombre, apellidos, mail, 0);

        if (estudianteDAO.guardar(est)) {
            JOptionPane.showMessageDialog(this, "Estudiante guardado con éxito.");
            limpiarCampos();
            cargarTabla();
        } else {
            JOptionPane.showMessageDialog(this, "Error al guardar en la base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
    }//GEN-LAST:event_btnGuardarActionPerformed
    }
