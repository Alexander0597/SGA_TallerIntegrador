    private void txtBuscarCiKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtBuscarCiKeyReleased
        // TODO add your handling code here:
        String cadenaFiltro = txtBuscarCi.getText().trim();
        if (trsFiltro != null) {
            if (cadenaFiltro.isEmpty()) {
                trsFiltro.setRowFilter(null); 
            } else {
                trsFiltro.setRowFilter(RowFilter.regexFilter("^" + cadenaFiltro, 0));
            }
        }
    }//GEN-LAST:event_txtBuscarCiKeyReleased

