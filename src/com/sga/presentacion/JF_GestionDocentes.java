    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String ci = txtCi.getText().trim();
        String nombre = txtNombre.getText().trim();
        String apellidos = txtApellidos.getText().trim();
        String mail = txtMail.getText().trim();

        if (ci.isEmpty() || nombre.isEmpty() || apellidos.isEmpty() || mail.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Docente doc = new Docente(ci, nombre, apellidos, mail);

        if (docenteDAO.guardar(doc)) {
            JOptionPane.showMessageDialog(this, "Docente guardado con éxito.");
            limpiarCampos();
            cargarTabla(); 
        } else {
            JOptionPane.showMessageDialog(this, "Error al guardar en la base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int filaSeleccionada = tblDocentes.getSelectedRow();
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un docente de la tabla para eliminar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int filaModelo = tblDocentes.convertRowIndexToModel(filaSeleccionada);
        String ci = tblDocentes.getModel().getValueAt(filaModelo, 0).toString();
        int confirmar = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar al docente con CI " + ci + "?", "Confirmar", JOptionPane.YES_NO_OPTION);

        if (confirmar == JOptionPane.YES_OPTION) {
            if (docenteDAO.eliminar(ci)) {
                JOptionPane.showMessageDialog(this, "Docente eliminado correctamente.");
                limpiarCampos();
                cargarTabla();
            } else {
                JOptionPane.showMessageDialog(this, "Error al eliminar de la base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

