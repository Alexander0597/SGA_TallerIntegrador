    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblDocentes.getModel();
        modelo.setRowCount(0); // Vaciar filas
        
        try {
            List<Docente> lista = docenteDAO.listarTodos();
            if (lista != null) {
                for (Docente doc : lista) {
                    Object[] fila = new Object[] {
                        doc.getCi(),
                        doc.getNombre(),
                        doc.getApellidos(),
                        doc.getMail()
                    };
                    modelo.addRow(fila);
                }
            }
            trsFiltro = new TableRowSorter<>(modelo);
            tblDocentes.setRowSorter(trsFiltro);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar la tabla: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limpiarCampos() {
        txtCi.setText("");
        txtNombre.setText("");
        txtApellidos.setText("");
        txtMail.setText("");
        txtCi.setEditable(true);
        tblDocentes.clearSelection();
    }

