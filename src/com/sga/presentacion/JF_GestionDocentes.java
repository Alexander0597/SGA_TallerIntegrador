    private void tblDocentesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblDocentesMouseClicked
        // TODO add your handling code here:
        int filaSeleccionada = tblDocentes.getSelectedRow();
        if (filaSeleccionada != -1) {
            int filaModelo = tblDocentes.convertRowIndexToModel(filaSeleccionada);
            Object ciObj = tblDocentes.getModel().getValueAt(filaModelo, 0);
            Object nomObj = tblDocentes.getModel().getValueAt(filaModelo, 1);
            Object apeObj = tblDocentes.getModel().getValueAt(filaModelo, 2);
            Object mailObj = tblDocentes.getModel().getValueAt(filaModelo, 3);
            
            txtCi.setText(ciObj != null ? ciObj.toString() : "");
            txtNombre.setText(nomObj != null ? nomObj.toString() : "");
            txtApellidos.setText(apeObj != null ? apeObj.toString() : "");
            txtMail.setText(mailObj != null ? mailObj.toString() : "");
            
            txtCi.setEditable(false); 
        }
    }//GEN-LAST:event_tblDocentesMouseClicked

