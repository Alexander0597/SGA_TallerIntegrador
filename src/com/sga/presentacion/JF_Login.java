    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        String usuario = txtUsuario.getText().trim();
        String contrasenia = new String(txtContrasenia.getPassword()).trim();

        // 1. Validar que los campos no estén vacíos
        if (usuario.isEmpty() || contrasenia.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                    "Por favor, ingrese el usuario y la contraseña.", 
                    "Campos Incompletos", 
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Autenticar en la base de datos sgaBD
        Persona adminLogueado = personaDAO.autenticar(usuario, contrasenia);

        if (adminLogueado != null) {
            String nombreCompleto = adminLogueado.getNombreCompleto();
            String ci = adminLogueado.getCi();

            javax.swing.JOptionPane.showMessageDialog(this, 
                    "¡Bienvenido(a) Administrador(a) " + nombreCompleto + "!", 
                    "Acceso Concedido", 
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);
            
            // 3. Abrir el Panel del Administrador
            JF_MenuPrincipal menu = new JF_MenuPrincipal(ci, "Administrador", nombreCompleto);
            menu.setVisible(true);
            this.dispose(); // Cierra la ventana de login
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, 
                    "Usuario o contraseña incorrectos.\n(Acceso exclusivo para Administradores)", 
                    "Error de Acceso", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnIngresarActionPerformed

